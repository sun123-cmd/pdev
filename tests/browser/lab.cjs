const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true,channel:"chrome"});
 const origin = process.env.FIBOLAB_TEST_URL || 'http://127.0.0.1:8080';
 const student = await browser.newContext();
 const teacher = await browser.newContext();
 const page = await student.newPage(); const board = await teacher.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message)); board.on('pageerror',e=>errors.push(e.message));
 await board.goto(origin+'/lab/?view=teacher');
 await page.goto(origin+'/lab/');
 await page.getByLabel('Display name').fill('Alex <script>');
 await page.getByRole('button',{name:'Join class'}).click();
 await page.getByLabel('Python code').fill(fs.readFileSync('tests/browser/correct.py','utf8'));
 await page.getByRole('button',{name:'Submit and run tests'}).click();
 await page.getByText('All output tests passed.',{exact:false}).waitFor();
 await board.getByText('Alex <script>',{exact:true}).waitFor({timeout:12000});
 assert.equal(await board.locator('#leaderboardList script').count(),0);
 await board.getByLabel('Teacher access key').fill('local-teacher-testing-2026');
 await board.getByRole('button',{name:'Unlock review'}).click();
 await board.getByRole('button',{name:'Review Alex <script>'}).click();
 await board.locator('#reviewPanel pre').first().waitFor();
 await board.getByRole('button',{name:'Confirm explanation'}).click();
 await board.getByText('TA verified',{exact:true}).first().waitFor();
 await page.reload();
 assert.match(await page.getByLabel('Python code').inputValue(),/def fibonacci/);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await board.screenshot({path:process.env.FIBOLAB_SCREENSHOT || '/tmp/fibolab-teacher.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await student.close(); await teacher.close();
 const offline=await browser.newPage();
 await offline.route('**/api/**',route=>route.abort());
 await offline.goto(origin+'/lab/');
 await offline.getByText('Offline',{exact:false}).first().waitFor();
 await offline.close();
 await browser.close(); console.log('PASS: student submission, shared board, teacher review/confirmation, draft persistence, mobile layout, offline state');
})().catch(e=>{console.error(e);process.exit(1)});
